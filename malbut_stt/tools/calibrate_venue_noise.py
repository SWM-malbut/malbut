"""Measure demo-hall ambient noise vs presenter speech and generate stt.yaml.

Supports live microphone capture (16 kHz mono via SoundDeviceRecorder) or
offline mono 16 kHz PCM16 WAV files (--ambient-wav / --speech-wav).
Optionally evaluates Silero VAD false-trigger rates before and after gating.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import struct
import sys
import wave
from typing import Any, Sequence

from malbut_stt.noise_guard import (
    HighPassFilter,
    NoiseAwareVad,
    NoiseFloorTracker,
    frame_rms_dbfs,
    recommend_venue_settings,
)


_FRAME_BYTES = 640  # 20 ms at 16 kHz mono PCM16.


def _read_pcm16_wav(path: Path) -> bytes:
    resolved = path.expanduser().resolve()
    if not resolved.is_file():
        raise ValueError(f'WAV file does not exist: {resolved}')
    with wave.open(str(resolved), 'rb') as wav:
        if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(),
                wav.getcomptype()) != (1, 2, 16000, 'NONE'):
            raise ValueError('WAV must be uncompressed mono 16 kHz PCM16')
        return wav.readframes(wav.getnframes())


def _record_live_pcm(device_index: int, duration_s: float) -> bytes:
    from malbut_stt.audio import SoundDeviceRecorder

    recorder = SoundDeviceRecorder(frame_length=512, device_index=device_index)
    target_samples = round(duration_s * 16000)
    chunks: list[bytes] = []
    collected = 0
    recorder.start()
    try:
        while collected < target_samples:
            samples = recorder.read()
            chunks.append(struct.pack(f'<{len(samples)}h', *samples))
            collected += len(samples)
    finally:
        recorder.stop()
        recorder.delete()
    return b''.join(chunks)[:target_samples * 2]


def _frame_dbfs_series(pcm: bytes, *, high_pass_hz: float = 100.0) -> list[float]:
    hpf = HighPassFilter(high_pass_hz) if high_pass_hz > 0.0 else None
    levels: list[float] = []
    for offset in range(0, len(pcm) - _FRAME_BYTES + 1, _FRAME_BYTES):
        frame = pcm[offset:offset + _FRAME_BYTES]
        filtered = hpf.process_pcm(frame) if hpf is not None else frame
        levels.append(frame_rms_dbfs(filtered))
    return levels


def _evaluate_silero(
    ambient_pcm: bytes,
    speech_pcm: bytes,
    params: dict[str, Any],
    model_path: Path,
) -> dict[str, float]:
    from malbut_stt.silero_stream import SileroStreamVad

    def _rate(detector: Any, pcm: bytes) -> float:
        detector.reset()
        total = hits = 0
        for offset in range(0, len(pcm) - _FRAME_BYTES + 1, _FRAME_BYTES):
            total += 1
            if detector.is_speech(pcm[offset:offset + _FRAME_BYTES], 16000):
                hits += 1
        return round(hits / total, 4) if total else 0.0

    baseline = SileroStreamVad(model_path, threshold=0.5)
    amb_base = _rate(baseline, ambient_pcm)
    sp_base = _rate(baseline, speech_pcm)

    tuned_silero = SileroStreamVad(model_path, threshold=float(params['vad_threshold']))
    tracker = NoiseFloorTracker()
    guarded = NoiseAwareVad(
        tuned_silero,
        min_rms_dbfs=float(params['vad_min_rms_dbfs']),
        snr_margin_db=float(params['vad_snr_margin_db']),
        sustain_margin_db=float(params['vad_sustain_margin_db']),
        hangover_frames=round(int(params['vad_hangover_ms']) / 20),
        high_pass_hz=float(params['high_pass_hz']),
        floor_tracker=tracker,
    )
    amb_guarded = _rate(guarded, ambient_pcm)
    # Keep the noise floor learned on ambient audio when measuring speech recall.
    sp_guarded = _rate(guarded, speech_pcm)
    return {
        'baseline_ambient_trigger_rate': amb_base,
        'guarded_ambient_trigger_rate': amb_guarded,
        'baseline_speech_active_rate': sp_base,
        'guarded_speech_active_rate': sp_guarded,
    }


def format_stt_yaml(parameters: dict[str, Any], report: dict[str, Any]) -> str:
    """Serialize ROS 2 parameter YAML compatible with ~/.config/malbut/stt.yaml."""
    lines = [
        '# Auto-generated by malbut_stt/tools/calibrate_venue_noise.py',
        f"# Verdict: {report['verdict'].upper()} — {report['verdict_detail']}",
        f"# Ambient p50/p90: {report['metrics']['ambient_p50_dbfs']} / "
        f"{report['metrics']['ambient_p90_dbfs']} dBFS | "
        f"Speech p90: {report['metrics']['speech_p90_dbfs']} dBFS | "
        f"SNR(p75-p90): {report['metrics']['snr_vs_ambient_p90_db']} dB",
        'malbut_stt:',
        '  ros__parameters:',
    ]
    for key, value in parameters.items():
        if isinstance(value, bool):
            formatted = 'true' if value else 'false'
        elif isinstance(value, str):
            formatted = value
        else:
            formatted = str(value)
        lines.append(f'    {key}: {formatted}')
    return '\n'.join(lines) + '\n'


def calibrate_pcm(
    ambient_pcm: bytes,
    speech_pcm: bytes,
    *,
    silero_model: Path | None = None,
) -> dict[str, Any]:
    """Analyze ambient and speech PCM recordings and return a calibration report."""
    ambient_levels = _frame_dbfs_series(ambient_pcm, high_pass_hz=100.0)
    speech_levels = _frame_dbfs_series(speech_pcm, high_pass_hz=100.0)
    report = recommend_venue_settings(ambient_levels, speech_levels)
    if silero_model is not None and silero_model.is_file():
        report['silero_simulation'] = _evaluate_silero(
            ambient_pcm, speech_pcm, report['ros_parameters'], silero_model)
    return report


def main(args: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--device-index', type=int, default=0,
                        help='SoundDevice input index for live capture (default: 0, XFM)')
    parser.add_argument('--duration-s', type=float, default=5.0,
                        help='Recording duration in seconds for each live phase (default: 5.0)')
    parser.add_argument('--ambient-wav', type=Path,
                        help='Offline mono 16 kHz PCM16 WAV of venue ambient noise')
    parser.add_argument('--speech-wav', type=Path,
                        help='Offline mono 16 kHz PCM16 WAV of presenter speech in the venue')
    parser.add_argument('--silero-model', type=Path,
                        help='Optional local silero-v6.2.3.onnx to simulate trigger reduction')
    parser.add_argument('--write-config', type=Path,
                        help='Write recommended ROS parameters YAML (e.g. ~/.config/malbut/stt.yaml)')
    parser.add_argument('--json-out', type=Path,
                        help='Optional path to save full JSON calibration report')
    options = parser.parse_args(args)

    if bool(options.ambient_wav) != bool(options.speech_wav):
        parser.error('--ambient-wav and --speech-wav must be supplied together')

    if options.ambient_wav and options.speech_wav:
        ambient_pcm = _read_pcm16_wav(options.ambient_wav)
        speech_pcm = _read_pcm16_wav(options.speech_wav)
    else:
        if options.duration_s < 1.0 or options.duration_s > 30.0:
            parser.error('--duration-s must be between 1.0 and 30.0')
        print(f'[1/2] 배경 소음 측정 ({options.duration_s:.1f}초) — 잠시 말하지 마세요...',
              file=sys.stderr, flush=True)
        ambient_pcm = _record_live_pcm(options.device_index, options.duration_s)
        print(f'[2/2] 시연 발화 측정 ({options.duration_s:.1f}초) — '
              '실제 시연 거리에서 "제이크야, 거실로 가. 오늘 날씨 알려줘"처럼 말하세요...',
              file=sys.stderr, flush=True)
        speech_pcm = _record_live_pcm(options.device_index, options.duration_s)

    silero_path = options.silero_model
    if silero_path is None:
        from malbut_stt.silero_stream import default_model_path

        candidate = default_model_path()
        if candidate.is_file():
            silero_path = candidate

    report = calibrate_pcm(ambient_pcm, speech_pcm, silero_model=silero_path)
    yaml_text = format_stt_yaml(report['ros_parameters'], report)

    if options.write_config is not None:
        target = options.write_config.expanduser()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(yaml_text, encoding='utf-8')
        report['written_config'] = str(target)

    if options.json_out is not None:
        json_target = options.json_out.expanduser()
        json_target.parent.mkdir(parents=True, exist_ok=True)
        json_target.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n',
                               encoding='utf-8')

    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
