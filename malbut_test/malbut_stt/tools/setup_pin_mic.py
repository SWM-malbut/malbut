"""Detect, verify, and configure a USB wireless lavalier mic (e.g. DJI Mic Mini) for STT.

Uses PulseAudio source matching so 48 kHz USB wireless mics are automatically
resampled to 16 kHz mono and work identically in both Web Bringup and terminal
Bringup without touching XFM homecam routing or the robot's USB speaker.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
from typing import Any, Sequence

import yaml

from malbut_stt.noise_guard import frame_rms_dbfs

_AUTO_HEADER = '# Auto-generated by malbut_stt/tools/setup_pin_mic.py'
_CONFLICTING_KEYS = frozenset({
    'aec_source',
    'aec_sink',
    'aec_calibration_audio',
    'aec_model_directory',
    'barge_in_pre_roll_s',
    'interruption_asr',
    'interruption_asr_timeout_s',
})


def _list_pulse(kind: str, env: dict[str, str]) -> list[dict[str, Any]]:
    result = subprocess.run(
        ['pactl', '--format=json', 'list', kind],
        env=env, capture_output=True, text=True, check=True, timeout=3,
    )
    items = json.loads(result.stdout)
    if not isinstance(items, list):
        raise RuntimeError(f'Invalid PulseAudio {kind} list')
    return items


def _get_default_sink(env: dict[str, str]) -> str:
    result = subprocess.run(
        ['pactl', 'get-default-sink'],
        env=env, capture_output=True, text=True, check=True, timeout=3,
    )
    return result.stdout.strip()


def _unmute_source(source_name: str, env: dict[str, str]) -> bool:
    result = subprocess.run(
        ['pactl', 'set-source-mute', source_name, '0'],
        env=env, capture_output=True, text=True, check=False, timeout=3,
    )
    return result.returncode == 0


def _match_sources(sources: list[dict[str, Any]], keyword: str) -> list[dict[str, Any]]:
    needle = keyword.casefold()
    matched = []
    for src in sources:
        props = src.get('properties', {})
        name = src.get('name', '')
        if not name or name.endswith('.monitor') or props.get('device.class') == 'monitor':
            continue
        haystack = ' '.join(str(part) for part in (
            name,
            src.get('description', ''),
            props.get('alsa.card_name', ''),
            props.get('alsa.name', ''),
            props.get('device.product.name', ''),
            props.get('device.vendor.name', ''),
        )).casefold()
        if needle in haystack:
            matched.append(src)
    return matched


def _probe_live_capture(source_name: str, duration_s: float) -> dict[str, Any]:
    from malbut_stt.audio import SoundDeviceRecorder

    previous_resolved = os.environ.get('MALBUT_STT_RESOLVED_PULSE_SOURCE')
    previous_pulse = os.environ.get('PULSE_SOURCE')
    os.environ['MALBUT_STT_RESOLVED_PULSE_SOURCE'] = source_name
    os.environ['PULSE_SOURCE'] = source_name
    recorder = None
    try:
        recorder = SoundDeviceRecorder(frame_length=512, device_index=0)
        recorder.start()
        target_chunks = max(10, round(duration_s * 16000 / 512))
        frame_levels: list[float] = []
        peak_abs = 0
        for _ in range(target_chunks):
            samples = recorder.read()
            peak_abs = max(peak_abs, max(abs(s) for s in samples))
            pcm = struct.pack(f'<{len(samples)}h', *samples)
            frame_levels.append(frame_rms_dbfs(pcm))
        return {
            'chunks_read': len(frame_levels),
            'sample_rate': recorder.sample_rate,
            'min_dbfs': round(min(frame_levels), 2),
            'max_dbfs': round(max(frame_levels), 2),
            'peak_ratio': round(peak_abs / 32768.0, 4),
            'clipping': peak_abs >= 32700,
            'silent': peak_abs <= 16,
        }
    finally:
        if recorder is not None:
            try:
                recorder.stop()
            finally:
                recorder.delete()
        if previous_resolved is None:
            os.environ.pop('MALBUT_STT_RESOLVED_PULSE_SOURCE', None)
        else:
            os.environ['MALBUT_STT_RESOLVED_PULSE_SOURCE'] = previous_resolved
        if previous_pulse is None:
            os.environ.pop('PULSE_SOURCE', None)
        else:
            os.environ['PULSE_SOURCE'] = previous_pulse


def _load_existing_parameters(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    document = yaml.safe_load(path.read_text(encoding='utf-8'))
    if not isinstance(document, dict):
        return {}
    params: dict[str, Any] = {}
    for scope in ('/**', 'malbut_stt'):
        section = document.get(scope)
        if isinstance(section, dict) and isinstance(section.get('ros__parameters'), dict):
            params.update(section['ros__parameters'])
    return params


def render_pin_mic_yaml(
    selector: str,
    *,
    resolved_name: str,
    base_parameters: dict[str, Any] | None = None,
) -> str:
    """Return ROS 2 parameter YAML compatible with ~/.config/malbut/stt.yaml."""
    merged: dict[str, Any] = {}
    if base_parameters:
        for key, value in base_parameters.items():
            if key not in _CONFLICTING_KEYS:
                merged[key] = value
    merged.update({
        'input_pulse_source': selector,
        'aec_backend': 'none',
        'barge_in_mode': 'legacy',
        'wake_input_gain': 1.0,
    })
    body = yaml.safe_dump({'/**': {'ros__parameters': merged}}, sort_keys=False, allow_unicode=True)
    return (
        f'{_AUTO_HEADER}\n'
        f'# Verified PulseAudio source: {resolved_name}\n'
        f'{body}'
    )


def main(args: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--match', default='DJI',
                        help='Case-insensitive keyword to match PulseAudio source (default: DJI)')
    parser.add_argument('--exact-source', default='',
                        help='Pin an exact PulseAudio source name instead of match:<keyword>')
    parser.add_argument('--probe-s', type=float, default=1.5,
                        help='Live 16 kHz capture probe duration in seconds (default: 1.5)')
    parser.add_argument('--skip-probe', action='store_true',
                        help='Only check PulseAudio routing without opening audio capture')
    parser.add_argument('--config-path', type=Path,
                        default=Path.home() / '.config/malbut/stt.yaml',
                        help='Target STT override YAML (default: ~/.config/malbut/stt.yaml)')
    parser.add_argument('--apply', action='store_true',
                        help='Write the verified wireless pin mic config to --config-path')
    parser.add_argument('--revert', action='store_true',
                        help='Restore backup or remove --config-path to revert STT to XFM')
    options = parser.parse_args(args)

    target = options.config_path.expanduser()
    backup = target.with_name(f'{target.name}.before-pin-mic')
    if options.revert:
        if backup.is_file():
            shutil.move(str(backup), str(target))
            print(json.dumps({
                'status': 'reverted',
                'config_path': str(target),
                'restored_from_backup': str(backup),
            }, ensure_ascii=False, indent=2))
            return 0
        removed = False
        if target.exists():
            target.unlink()
            removed = True
        print(json.dumps({'status': 'reverted', 'config_path': str(target), 'removed': removed},
                         ensure_ascii=False, indent=2))
        return 0

    env = dict(os.environ)
    sources = _list_pulse('sources', env)
    sinks = _list_pulse('sinks', env)
    default_sink = _get_default_sink(env)

    if options.exact_source.strip():
        selector = options.exact_source.strip()
        matched = [s for s in sources if s.get('name') == selector
                   and not s.get('name', '').endswith('.monitor')]
    else:
        keyword = options.match.strip()
        if not keyword:
            parser.error('--match must be nonempty')
        selector = f'match:{keyword}'
        matched = _match_sources(sources, keyword)

    if len(matched) != 1:
        available = [s.get('name') for s in sources
                     if s.get('name') and not s.get('name', '').endswith('.monitor')]
        print(json.dumps({
            'status': 'not_found',
            'selector': selector,
            'matched': [s.get('name') for s in matched],
            'available_sources': available,
            'hint': '수신기(RX) 전원·페어링과 USB 데이터 케이블(충전 전용 불가)을 확인하세요.',
        }, ensure_ascii=False, indent=2))
        return 1

    resolved = matched[0]['name']
    unmuted = False
    if matched[0].get('mute') is True:
        unmuted = _unmute_source(resolved, env)

    speaker_warning = None
    keyword_cf = (options.match or 'dji').strip().casefold()
    if default_sink == 'auto_null' or not any(
        s.get('name') and s.get('name') != 'auto_null' for s in sinks
    ):
        speaker_warning = {
            'message': '물리 스피커(USB 스피커)가 연결되어 있지 않습니다 (현재 auto_null 무음 출력).',
            'current_default_sink': default_sink,
            'fix_hint': '로봇 USB 스피커 허브 케이블이 뽑혀 있지 않은지 확인하고 다시 연결하세요.',
        }
    elif keyword_cf and keyword_cf in default_sink.casefold():
        other_sinks = [s.get('name') for s in sinks
                       if s.get('name') and s.get('name') != 'auto_null'
                       and keyword_cf not in s.get('name', '').casefold()]
        speaker_warning = {
            'message': '기본 스피커(default sink)가 무선 마이크 장치로 바뀌어 있습니다.',
            'current_default_sink': default_sink,
            'other_sinks': other_sinks,
            'fix_command': (f"pactl set-default-sink '{other_sinks[0]}'"
                            if other_sinks else 'pactl list short sinks'),
        }

    probe = None
    if not options.skip_probe:
        print(f'[확인] {resolved} 에서 16 kHz 스트림 {options.probe_s:.1f}초 측정 중... '
              '(마이크에 "제이크야" 한 번 말해보세요)', file=sys.stderr, flush=True)
        probe = _probe_live_capture(resolved, options.probe_s)

    report: dict[str, Any] = {
        'status': 'ok',
        'selector': selector,
        'resolved_source': resolved,
        'unmuted': unmuted,
        'default_sink': default_sink,
        'speaker_warning': speaker_warning,
        'probe': probe,
    }
    if options.apply:
        target.parent.mkdir(parents=True, exist_ok=True)
        source_for_merge = backup if backup.is_file() else target
        if target.is_file() and not backup.exists():
            existing_text = target.read_text(encoding='utf-8')
            if not existing_text.startswith(_AUTO_HEADER):
                shutil.copy2(str(target), str(backup))
                report['backup_config'] = str(backup)
        base_params = _load_existing_parameters(source_for_merge)
        target.write_text(
            render_pin_mic_yaml(selector, resolved_name=resolved, base_parameters=base_params),
            encoding='utf-8',
        )
        report['written_config'] = str(target)

    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
